t('Contribution consumes Share/Mix periods', app.includes('const cb = an.share && an.share.baselinePeriod') && app.includes('const cc = an.share && an.share.currentPeriod'));
console.log(checks.map(x=>`${x.ok?'PASS':'FAIL'} ${x.name}${x.detail?' — '+x.detail:''}`).join('\n'));
console.log(`\n${checks.filter(x=>x.ok).length}/${checks.length} PASS`);
if(checks.some(x=>!x.ok))process.exit(1);
