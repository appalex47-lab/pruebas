const mom15=T.comparisonRanges(oct15,'month','2026-10-15').find(x=>x.id==='mom');
t('Oct 1-15 → Sep 1-15', mom15.range.from==='2026-09-01' && mom15.range.to==='2026-09-15', JSON.stringify(mom15.range));
const full={from:'2026-10-01',to:'2026-10-31',partial:false,key:'2026-10'};
const momFull=T.comparisonRanges(full,'month','2026-10-31').find(x=>x.id==='mom');
