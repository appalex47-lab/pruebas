const T=ctx.FP.temporalEngine;
const checks=[];
const t=(name,ok,detail='')=>checks.push({name,ok,detail});
const oct={from:'2026-10-01',to:'2026-10-06',partial:true,key:'2026-10'};
const mom=T.comparisonRanges(oct,'month','2026-10-06').find(x=>x.id==='mom');
const yoy=T.comparisonRanges(oct,'month','2026-10-06').find(x=>x.id==='yoy');
