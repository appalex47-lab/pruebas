const app=fs.readFileSync('js/app.js','utf8');
t('Share/Mix uses exact comparison for partial focus', app.includes('if (focus?.partial && TE)') && app.includes("const curMap = await FP.productStore.aggregate({ ...focus") && app.includes('const baseMap = await FP.productStore.aggregate({ ...cmp.range'));
