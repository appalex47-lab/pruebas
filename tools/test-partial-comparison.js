const fs=require('fs'),vm=require('vm'),assert=require('assert');
const ctx={console};ctx.globalThis=ctx;ctx.FP={config:{calendar:{monthNamesEs:['Enero','Febrero','Marzo','Abril','Mayo','Junio','Julio','Agosto','Septiembre','Octubre','Noviembre','Diciembre'],dayNamesEs:['Lunes','Martes','Miércoles','Jueves','Viernes','Sábado','Domingo'],dayNames:['Mon','Tue','Wed','Thu','Fri','Sat','Sun'],fortnightSplitDay:15}}};
